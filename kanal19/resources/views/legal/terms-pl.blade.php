    <h2>1. Postanowienia ogólne</h2>
    <ol>
        <li>Regulamin określa zasady korzystania z portalu internetowego i aplikacji Kanał 19 dostępnych pod adresem kanal19.pl (dalej: „Portal”).</li>
        <li>Operatorem Portalu jest <x-operator :op="$op" /> (dalej: „Operator”).</li>
        <li>Portal jest przeznaczony dla kierowców zawodowych, firm transportowych i innych pracodawców, sprzedających pojazdy oraz reklamodawców.</li>
        <li>Do korzystania z Portalu potrzebne jest urządzenie z dostępem do internetu i aktualną przeglądarką. Niektóre funkcje (mapa, tryb jazdy, SOS, powiadomienia, CB głosowe) wymagają zgody na dostęp do lokalizacji, powiadomień lub mikrofonu.</li>
    </ol>

    <h2>2. Usługi</h2>
    <p>W ramach Portalu Operator udostępnia w szczególności:</p>
    <ul>
        <li>ogłoszenia o pracy dla kierowców i bazę kierowców,</li>
        <li>giełdę pojazdów (sprzedaż pojazdów nowych, używanych i poleasingowych),</li>
        <li>mapę kierowców – parkingi, ceny paliwa, utrudnienia na drogach i wezwania SOS,</li>
        <li>tryb jazdy z ostrzeżeniami o zgłoszeniach innych kierowców,</li>
        <li>planer trasy dla ciężarówek i autobusów,</li>
        <li>CB Kanał 19 – kanały tekstowe i głosowe,</li>
        <li>powiadomienia o wezwaniach SOS w pobliżu,</li>
        <li>aktualności, poradniki i kalkulatory,</li>
        <li>kampanie reklamowe dla reklamodawców.</li>
    </ul>
    <p>Korzystanie z Portalu przez kierowców jest bezpłatne. Zamieszczanie ogłoszeń o pracy i pojazdów jest bezpłatne, chyba że przy danej usłudze wyraźnie wskazano inaczej. Warunki i ceny kampanii reklamowych ustalane są indywidualnie z reklamodawcą.</p>

    <h2>3. Konto</h2>
    <ol>
        <li>Założenie konta wymaga podania prawdziwych danych, adresu e-mail, numeru telefonu oraz akceptacji Regulaminu i Polityki prywatności. Operator może wymagać potwierdzenia numeru telefonu kodem SMS.</li>
        <li>Jedna osoba lub firma może mieć jedno konto danego rodzaju. Nie wolno udostępniać konta innym osobom.</li>
        <li>Użytkownik może w każdej chwili usunąć konto w zakładce „Moje konto”. Usunięcie konta trwale usuwa ogłoszenia, zgłoszenia i wiadomości użytkownika.</li>
        <li>Operator może zablokować konto użytkownika, który narusza Regulamin lub prawo, w szczególności podaje fałszywe dane, publikuje fałszywe zgłoszenia lub wezwania SOS albo treści bezprawne.</li>
    </ol>

    <h2>4. Ogłoszenia o pracy i pojazdach</h2>
    <ol>
        <li>Ogłoszenie przed publikacją można podejrzeć i poprawić. Po publikacji jest widoczne przez 30 dni i <strong>nie może być edytowane przez użytkownika</strong> – zmiany wprowadza wyłącznie Operator na wniosek.</li>
        <li>Ogłoszenie musi dotyczyć rzeczywistej oferty pracy lub rzeczywistego pojazdu, zawierać prawdziwe informacje (w tym wynagrodzenie i cenę) i nie może dyskryminować kandydatów.</li>
        <li>Firma widzi w bazie kierowców imię, pierwszą literę nazwiska, doświadczenie i uprawnienia. Numer telefonu kierowcy jest udostępniany dopiero, gdy kierowca przyjmie zaproszenie firmy albo sam zaaplikuje na ofertę.</li>
        <li>Operator nie jest stroną umów zawieranych między użytkownikami (umów o pracę, zlecenia, sprzedaży pojazdów) i nie odpowiada za ich wykonanie.</li>
    </ol>

    <h2>5. Mapa, zgłoszenia, tryb jazdy i SOS</h2>
    <ol>
        <li><strong>Funkcja SOS nie zastępuje numeru alarmowego.</strong> W sytuacji zagrożenia życia, zdrowia lub mienia należy natychmiast dzwonić pod numer 112. Wezwanie SOS w Portalu trafia wyłącznie do innych użytkowników, którzy mogą, ale nie muszą, pomóc.</li>
        <li>Zgłoszenia na mapie (parkingi, paliwo, utrudnienia, kontrole) pochodzą od użytkowników. Operator nie gwarantuje ich prawdziwości, kompletności ani aktualności. Zgłoszenia znikają automatycznie po czasie zależnym od ich rodzaju i mogą być potwierdzane lub usuwane głosami innych kierowców.</li>
        <li>Zabronione jest publikowanie fałszywych zgłoszeń i wezwań SOS.</li>
        <li><strong>Nie korzystaj z telefonu w ręce podczas jazdy.</strong> Zgłoszeń dokonuj na postoju albo przy pomocy pasażera; podczas jazdy korzystaj z uchwytu i zestawu głośnomówiącego zgodnie z przepisami ruchu drogowego.</li>
        <li>Planer trasy ma charakter pomocniczy. Trasa jest liczona na podstawie danych OpenStreetMap i zgłoszeń użytkowników, które mogą być niepełne. Kierowca zawsze stosuje się do znaków drogowych i przepisów oraz sam odpowiada za dobór trasy do swojego pojazdu.</li>
    </ol>

    <h2>6. CB Kanał 19</h2>
    <ol>
        <li>Wiadomości tekstowe są widoczne dla wszystkich na danym kanale przez 3 godziny, potem znikają. Wiadomość zgłoszona przez 3 użytkowników jest ukrywana.</li>
        <li>Rozmowy głosowe odbywają się na żywo i nie są nagrywane przez Operatora.</li>
        <li>Na CB zabronione są wulgaryzmy, groźby, mowa nienawiści, reklama bez zgody Operatora oraz podawanie danych osobowych innych osób.</li>
    </ol>

    <h2>6a. Opinie o pracodawcach</h2>
    <ol>
        <li>Kierowca z potwierdzonym kontem może dodać jedną opinię o firmie i ją później zmienić lub usunąć. Opinia jest podpisana imieniem i pierwszą literą nazwiska.</li>
        <li>Opinia musi dotyczyć własnych doświadczeń, być prawdziwa i rzeczowa. Zabronione są wulgaryzmy, groźby, ujawnianie danych osobowych innych osób i opinie pisane na zlecenie.</li>
        <li>Firma może publicznie odpowiedzieć na opinię. Opinia zgłoszona przez 3 użytkowników jest ukrywana do czasu sprawdzenia przez Operatora.</li>
    </ol>

